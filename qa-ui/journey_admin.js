  await page.getByLabel('Temporary password').fill('qa-password-1234');
  await page.getByLabel('Role').selectOption('member');
  await page.locator('.dlg label.ck', { hasText: 'design' }).locator('input').check().catch(() => {});
  await page.locator('.dlg').getByRole('button', { name: 'Add person' }).click();
  await page.waitForTimeout(1000);
  step('add person', await toasts());
  await page.getByPlaceholder('Name, email or group').fill(process.env.QAUSER || 'qa-xss2');
  await page.waitForTimeout(300);
  step('users search', await page.locator('table').innerText());
  await page.screenshot({ path: 'shots/a_users_xss.png' });
  await page.getByRole('button', { name: 'Edit' }).first().click();
  await page.getByLabel('Storage quota (GB)').fill('0.1');
  await page.locator('.dlg').getByRole('button', { name: 'Save' }).click();
  await page.waitForTimeout(900);
  step('edit quota', await toasts());
  step('row after quota', await page.locator('table tbody tr').first().innerText());
